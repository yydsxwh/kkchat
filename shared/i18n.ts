export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { zh, en };

export function normalizeLocale(value: string | null | undefined): Locale {
  const text = String(value || "").toLowerCase();
  if (text.startsWith("zh")) return "zh";
  if (text.startsWith("en")) return "en";
  return "en";
}

/** Accept-Language：中文优先给中文，其余语言给英文。 */
export function localeFromAcceptLanguage(header: string | null | undefined): Locale {
  const first = String(header || "").split(",")[0]?.trim();
  return first ? normalizeLocale(first) : "zh";
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[locale]?.[key] ?? zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] != null ? String(vars[name]) : `{${name}}`));
}

/** 服务器存 UTC；按设备时区显示。时区不影响排序、授权或好友状态。 */
export function formatMessageTime(iso: string | null, locale: Locale, now = new Date()): string {
  if (!iso) return "";
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "";
  const tag = locale === "zh" ? "zh-CN" : "en-US";
  const sameDay = date.toDateString() === now.toDateString();
  if (sameDay) return new Intl.DateTimeFormat(tag, { hour: "2-digit", minute: "2-digit" }).format(date);
  return new Intl.DateTimeFormat(tag, { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }).format(date);
}
